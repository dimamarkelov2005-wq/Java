package linear;

public class ArithmeticOperations {
    public static void main(String[] args) {

        int x = 12;
        int y = 4;

        System.out.println("Сложение: " + (x + y));
        System.out.println("Умножение: " + (x * y));
        System.out.println("Деление: " + ((double) x / y));
    }
}
