package linear;

public class ExecutionOrder {
    public static void main(String[] args) {

        int a = 3;
        int b = 7;
        int c = 10;

        int sum = a + b + c;

        System.out.println("a = " + a);
        System.out.println("b = " + b);
        System.out.println("c = " + c);
        System.out.println("Сумма: " + sum);
    }
}
